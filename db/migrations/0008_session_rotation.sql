-- ============================================================
-- 0008: セッション・シークレットのローテーション（盗用検知）
-- ============================================================
-- 継続利用中に一定間隔でCookieのシークレットを更新し、盗まれた古いトークンが
-- 後から使われたら検知して当該セッションを失効させる。
--   prev_token_hash: 直前のシークレットのハッシュ（並行リクエスト用の猶予＆盗用検知に使用）
--   rotated_at:      最後にローテーションした時刻
-- 空DB・再実行に安全。
-- ============================================================

alter table auth_sessions add column if not exists prev_token_hash text;
alter table auth_sessions add column if not exists rotated_at timestamptz;
